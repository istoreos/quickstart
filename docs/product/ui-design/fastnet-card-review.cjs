// Review the integrated homepage card served by scripts/ui-design.sh.
const {chromium}=require('playwright')
const assert=require('node:assert/strict'),fs=require('node:fs/promises'),path=require('node:path'),os=require('node:os')
async function main(){
 const output=process.env.OUTPUT_DIR||path.join(os.tmpdir(),'quickstart-fastnet-card-v2')
 await fs.mkdir(output,{recursive:true})
 const browser=await chromium.launch({headless:true,args:['--no-sandbox'],...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})})
 const page=await browser.newPage({viewport:{width:1600,height:1100}}),errors=[],requests=[],checks=[]
 page.on('pageerror',e=>errors.push(e.message))
 page.on('request',r=>{const u=new URL(r.url());if(u.pathname.startsWith('/cgi-bin/')||!['127.0.0.1','localhost'].includes(u.hostname))requests.push(r.url())})
 const card=()=>page.locator('[data-fastnet-card]'),test=()=>page.locator('[data-fastnet-test]')
 const visit=async(scene='ready',extra='')=>{await page.goto(`${process.env.PREVIEW_URL||'http://127.0.0.1:5180'}/?fastnet=${scene}${extra}`);await card().waitFor()}
 const screenshot=async name=>{await card().scrollIntoViewIfNeeded();await page.screenshot({path:path.join(output,name+'.png')})}
 const apply=async()=>{await page.locator('[data-apply]').click();if(await page.locator('[data-confirm-finish]').count())await page.locator('[data-confirm-finish]').click();await page.locator('[data-cancel]').waitFor({state:'hidden'})}
 let failure
 try{
  await visit()
  assert.equal(await page.locator('[data-ordered-card=fastnet] [data-layout-card=fastnet] [data-fastnet-card]').count(),1)
  assert.equal(await page.locator('.fn-review,.fn-discover').count(),0)
  for(const id of ['traffic','devices','docker'])assert.equal(await page.locator(`[data-ordered-card=${id}]`).count(),1)
  const size=await card().boundingBox(),home=await page.locator('.ordered-content').boundingBox()
  assert.ok(size.width<home.width*.55,'FastNet should be a peer card, not a full-width hero')
  assert.ok(size.height<350,'The card should stay compact beside its peer')
  assert.match(await card().innerText(),/上次下载[\s\S]*942[\s\S]*上次上传[\s\S]*108/)
  assert.match(await card().innerText(),/今天 14:22[\s\S]*NAT[\s\S]*全锥形[\s\S]*IPv6[\s\S]*可用/)
  assert.doesNotMatch(await card().innerText(),/LAN|局域网|历史趋势/)
  await screenshot('01-home-integrated');await card().screenshot({path:path.join(output,'02-card.png')})
  checks.push('首页统一槽位内的独立卡片，与流量、设备、Docker 共存；非整行展示；只包含外网信息')
  await test().click()
  assert.equal(await page.getByRole('dialog').count(),0)
  assert.equal(await test().isDisabled(),true)
  assert.match(await card().innerText(),/942/)
  await screenshot('03-in-card-progress')
  await card().getByRole('button',{name:'停止',exact:true}).click()
  assert.match(await card().innerText(),/942/)
  await test().click();await card().getByText('测速完成',{exact:true}).waitFor()
  assert.match(await card().innerText(),/946[\s\S]*109[\s\S]*刚刚/)
  checks.push('卡片测速按钮直接执行，原位进度、防重复点击、停止保留旧结果，完成更新速率与时间')
  await visit('error');await test().click();await card().getByRole('alert').waitFor()
  assert.match(await card().innerText(),/942/)
  await card().getByRole('button',{name:'重试',exact:true}).click();await card().getByText('测速完成',{exact:true}).waitFor()
  checks.push('测速失败保留上次结果，卡片内显式重试')
  await visit('missing');await card().locator('[data-fastnet-install]').click()
  assert.equal(await card().locator('[data-fastnet-install]').isDisabled(),true)
  await test().waitFor();assert.match(await card().innerText(),/尚未测速/)
  assert.equal(await card().locator('.fastnet-progress').count(),0)
  await visit('install-error');await card().locator('[data-fastnet-install]').click();await card().getByRole('alert').waitFor()
  await card().getByRole('button',{name:'重试安装',exact:true}).click();await test().waitFor()
  checks.push('缺少组件时原卡片安装，安装不自动测速；安装失败可原位重试')
  await visit('empty');assert.match(await card().innerText(),/尚未测速[\s\S]*未检测/)
  await visit('stale');assert.match(await card().innerText(),/3 天前[\s\S]*结果较早/)
  await visit('partial');assert.match(await card().innerText(),/部分可用/)
  await visit('stopped');assert.equal(await test().count(),0)
  await card().getByRole('button',{name:'启用服务',exact:true}).click();await test().waitFor()
  assert.equal(await card().locator('.fastnet-progress').count(),0)
  checks.push('无结果不填零；旧结果带时间；IPv6 部分异常；启用服务不自动测速')
  await visit();await page.getByRole('button',{name:'自定义首页',exact:true}).click()
  await page.locator('[data-display-settings=fastnet]').click()
  await page.locator('[data-presentation-form=summary]').click();await page.locator('[data-adopt-display]').click()
  assert.equal(await page.locator('[data-layout-card=fastnet]').getAttribute('data-presentation'),'summary')
  await page.locator('[data-hide-module=fastnet]').click();assert.equal(await card().count(),0)
  await page.locator('[data-open-library]').click();await page.locator('[data-choice=fastnet]').click()
  await page.locator('[data-confirm-choice]').click();await apply()
  assert.equal(await page.locator('[data-ordered-card=fastnet]').count(),1)
  assert.notEqual(await page.locator('[data-ordered-row]').filter({has:card()}).getAttribute('data-row-source'),'internet')
  assert.match(await card().innerText(),/942/)
  checks.push('复用首页显示设置、摘要、隐藏、模块库重新添加和位置保存；只有一张卡片且结果保留')
  await visit();await card().getByRole('button',{name:'外网测速更多操作',exact:true}).click()
  await page.getByRole('menuitem',{name:'查看上次结果',exact:true}).click()
  assert.match(await page.getByRole('dialog').innerText(),/路由器 → 互联网/)
  await page.keyboard.press('Escape');await page.getByRole('dialog').waitFor({state:'hidden'})
  checks.push('详情复用首页对话框，Escape 关闭；快捷测速仍在原卡片')
  for(const [width,theme] of [[390,'light'],[320,'dark']]){
   await page.setViewportSize({width,height:900});await visit('ready',`&theme=${theme}`)
   await screenshot(`04-mobile-${width}-${theme}`)
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
   const b=await card().boundingBox();assert.ok(b.x>=0&&b.x+b.width<=width)
   await card().screenshot({path:path.join(output,`05-card-${width}-${theme}.png`)})
  }
  checks.push('390px 浅色、320px 深色下自动排列，卡片与页面均无横向溢出')
  assert.deepEqual(errors,[]);assert.deepEqual(requests,[])
  checks.push('无页面异常；无真实路由器、安装或测速请求')
 }catch(e){failure=e.stack;process.exitCode=1;await page.screenshot({path:path.join(output,'failure.png')}).catch(()=>{})}
 finally{await browser.close();const report={result:failure?'failed':'passed',checks,errors,requests,...(failure?{failure}:{})};await fs.writeFile(path.join(output,'report.json'),JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify({...report,output},null,2))}
}
main().catch(e=>{console.error(e);process.exitCode=1})
