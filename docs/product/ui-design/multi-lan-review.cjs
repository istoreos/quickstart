// Design interaction review. Requires a running scripts/ui-design.sh preview
// and Playwright on NODE_PATH. CHROMIUM_PATH can reuse an installed browser.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')

async function main() {
  const output = process.env.OUTPUT_DIR || path.join(os.tmpdir(), 'quickstart-multi-lan-review')
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({
    headless: true,
    ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}),
    args: ['--no-sandbox'],
  })
  const errors = [], unexpectedRequests = [], checks = []
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
    page.on('pageerror', e => errors.push(e.message))
    page.on('request', request => {
      const url = new URL(request.url())
      if (url.pathname.startsWith('/cgi-bin/') || !['127.0.0.1', 'localhost'].includes(url.hostname)) unexpectedRequests.push(request.url())
    })
    const choose = name => page.getByRole('complementary', { name: '选择局域网' }).getByRole('button', { name: new RegExp(name) }).click()
    const rows = page.locator('tbody tr')
    await page.goto(`${process.env.PREVIEW_URL || 'http://127.0.0.1:5180'}/design/multi-lan`)
    await page.waitForSelector('.multi-lan')
    assert.equal(await rows.count(), 7)
    assert.equal(await page.locator('tbody .mac').filter({ hasText: '02:00:00:00:02:01' }).count(), 2)
    await page.screenshot({ path: path.join(output, 'overview.png'), fullPage: true })
    checks.push('总览分别列出 7 条网络接入记录，跨网同 MAC 保留两条')

    await choose('办公网络')
    assert.equal(await rows.count(), 2)
    assert.equal(new URL(page.url()).searchParams.get('network'), 'lan1')
    await page.getByRole('textbox', { name: '搜索设备' }).fill('工作站')
    assert.equal(await rows.count(), 1)
    await page.getByRole('button', { name: '详情 ›', exact: true }).click()
    assert.match(await page.locator('.drawer').innerText(), /办公网络.*lan1/)
    await page.getByRole('button', { name: '预览限速设置', exact: true }).click()
    assert.match(await page.locator('.plan').innerText(), /办公网络.*lan1/)
    await page.getByRole('button', { name: '确认应用（演示）', exact: true }).click()
    assert.match(await rows.innerText(), /限速 50 Mbps/)
    await choose('访客网络')
    assert.match(await page.locator('tbody').innerText(), /默认上网/)
    assert.doesNotMatch(await page.locator('tbody').innerText(), /限速 50/)
    checks.push('LAN 筛选、URL、搜索及限速演示限定于 lan1；lan2 同 MAC 策略未改变')

    await page.getByRole('button', { name: '局域网设置', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: '预览修改', exact: true }).isDisabled(), true)
    await choose('办公网络')
    await page.locator('.setting input').first().fill('192.168.10.110')
    await page.getByRole('button', { name: '预览修改', exact: true }).click()
    assert.match(await page.locator('.plan').innerText(), /多个网络共用/)
    await page.getByRole('button', { name: '确认应用（演示）', exact: true }).click()
    await page.screenshot({ path: path.join(output, 'lan1-settings.png'), fullPage: true })
    await choose('家庭网络')
    assert.equal(await page.locator('.setting input').first().inputValue(), '192.168.1.100')
    await choose('办公网络')
    assert.equal(await page.locator('.setting input').first().inputValue(), '192.168.10.110')
    checks.push('外部 DHCP 只读；本地 DHCP 预览提示共用服务，示例草稿和应用值按 LAN 分离')

    await page.getByRole('combobox').first().selectOption('no-default')
    assert.equal(await rows.count(), 4)
    assert.equal(await page.getByRole('complementary', { name: '选择局域网' }).getByRole('button', { name: /家庭网络/ }).count(), 0)
    await page.getByRole('combobox').first().selectOption('partial')
    await choose('办公网络')
    await page.getByRole('button', { name: '详情 ›', exact: true }).first().click()
    assert.equal(await page.getByRole('button', { name: '预览限速设置', exact: true }).isDisabled(), true)
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('.drawer').count(), 0)
    await choose('家庭网络')
    await page.getByRole('button', { name: '详情 ›', exact: true }).first().click()
    assert.equal(await page.getByRole('button', { name: '预览限速设置', exact: true }).isEnabled(), true)
    await page.keyboard.press('Escape')
    await choose('待确认归属')
    assert.equal(await rows.count(), 1)
    await page.getByRole('button', { name: '详情 ›', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: '预览限速设置', exact: true }).isDisabled(), true)
    await page.keyboard.press('Escape')
    checks.push('无默认 lan、lan1 服务异常、其他网络仍可操作、未知归属锁定和 Escape 关闭均通过')

    await page.getByRole('combobox').first().selectOption('normal')
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true })
    await choose('办公网络')
    await page.getByRole('button', { name: '局域网设置', exact: true }).click()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: path.join(output, 'mobile-settings.png'), fullPage: true })
    await page.setViewportSize({ width: 1600, height: 1000 })
    await page.goto('http://127.0.0.1:5180/design/multi-lan?theme=dark')
    await page.waitForSelector('.multi-lan')
    assert.equal(await page.locator('.multi-lan').evaluate(el => getComputedStyle(el).getPropertyValue('--ml-bg').trim()), '#23262e')
    await page.screenshot({ path: path.join(output, 'dark.png'), fullPage: true })
    checks.push('390px 总览/设置无页面横向溢出，保存桌面/移动/深色截图')
    assert.deepEqual(errors, [])
    assert.deepEqual(unexpectedRequests, [])
    const result = { status: 'passed', checks, pageErrors: errors, unexpectedRequests }
    await fs.writeFile(path.join(output, 'review.json'), JSON.stringify(result, null, 2) + '\n')
    console.log(JSON.stringify(result, null, 2))
  } finally {
    await browser.close()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
